import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const shortcutsDir = path.resolve(here, "..", "..", "..", "shortcuts");
const outFile = path.resolve(here, "..", "src", "shortcuts-data.js");

const files = fs.readdirSync(shortcutsDir).filter((f) => f.endsWith(".shortcut")).sort();
if (!files.length) throw new Error("no .shortcut files in " + shortcutsDir);

const entries = files.map((f) => {
  const b64 = fs.readFileSync(path.join(shortcutsDir, f)).toString("base64");
  return `  ${JSON.stringify(f)}: ${JSON.stringify(b64)},`;
});

const src = `// AUTO-GENERATED by scripts/gen-shortcuts.mjs — do not edit.
// Binary iOS Shortcuts served at GET /shortcuts/<name>
export const SHORTCUT_FILES = {
${entries.join("\n")}
};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, src, "utf8");
console.log(`wrote ${path.relative(process.cwd(), outFile)} (${files.join(", ")})`);
